// Package configref generates the fully-commented reference config.yaml that
// `fab config explain` prints to stdout, and exposes the same schema as a
// machine-readable field table (`--json`). The reference is the single
// discoverability surface for the config.yaml schema — it documents BOTH the
// binary-consumed keys (modeled on internal/config.Config) and the
// skill-consumed keys (read by markdown skills, invisible to Go reflection).
//
// METADATA TABLE, NOT A PROSE TEMPLATE. The schema is modeled as an ordered
// per-field metadata table (the Fields registry): each entry carries the field's
// canonical default, expected YAML kind, one-line description, scope (project/system/both), advertise
// flag, renamed_from carry-forward, AND the rendered YAML segment (the commented
// block that documents the field in the reference). Both renderings — the
// commented YAML and the JSON dump — are generated by walking that one table:
// Render() concatenates each row's Segment in table order, RenderJSON() marshals
// each row's metadata. There is no second copy of the schema and no monolithic
// template to drift against the table. This is Change 1 of the config-upgrade
// effort; the scope/advertise/renamed_from metadata is consumed by the downstream
// cascade resolver, `fab config init --system`, and `fab config upgrade`
// (Changes 2-3). See docs/specs/config.md.
//
// GENERATED, NOT HAND-WRITTEN. Every default value that has a canonical Go
// symbol is sourced from that symbol, never copied — the built-in providers via
// agent.ResolveProvider over agent.ProviderNames (so the provider SET is derived
// too, not a hand-maintained name list), the per-role default profiles via
// agent.DefaultProfile over agent.RoleNames, the pipeline stage names via
// agent.StageNames, and the pane-worker column width via
// config.DefaultDispatchColumnWidth. The dynamic segments (providers, agent, stage_hooks)
// interpolate those same symbols when the row is built, so the reference text
// carries no literal copy of any value. The providers SEGMENT still names the
// four built-ins one by one (via agent.DefaultInteractiveCommand and the
// agent.DefaultCodex*/DefaultAgy*/DefaultKimi* vars) because its per-provider
// commentary is bespoke prose, not a derivable projection — only the values are
// interpolated.
//
// ADVERTISED SURFACE vs. FULL REFERENCE. `advertise` decides only what the managed
// fence scaffolds into every project's config.yaml. As of 260806-j9nh the advertised
// agent surface is exactly the two depth knobs (agent.session, agent.workers); the
// machinery beneath them — agent.profiles and the whole providers table — is
// demoted to advertise:false, so it no longer costs ~90 commented lines in every
// repo. It keeps its registry rows, its --json defaults, and its rendered segments,
// because `fab config explain` is the canonical full schema surface and
// `fab config init --system` renders from those same segments.
//
// Canonical default vs. rendering example: a field's Default holds the CANONICAL
// built-in default (what the downstream cascade falls back to), not the value the
// reference happens to show as an example. source_paths/test_paths render an
// example (`- src/`, `- "**/*_test.go"`) but their binary default is empty, so
// their Default is nil — the example lives in the rendered Segment, not in the
// metadata.
//
// Empty-default convention: a field with no meaningful built-in default carries a
// nil Default (JSON `null`), NOT a typed empty (`[]`, `{}`, `""`). The nil is the
// uniform "no built-in default — the cascade falls back to absent" signal the
// downstream resolver (Change 2) consumes; distinguishing []string{} from nil
// would leak an implementation detail with no cascade meaning. A non-nil Default
// therefore always denotes a real built-in value (the four built-in providers'
// command grammars AND their per-role fills, the resolved per-role profiles, the
// two depth knobs' claude, dispatch.mode's native, dispatch.column_width's 35,
// dispatch.reap_done's true).
// The convention still governs WITHIN a provider: codex's and agy's fill maps are
// SPARSE, so a role fab-kit ships no fill for is simply absent rather than emitted
// as an empty object — and kimi, which ships no fills at all, projects no fill map
// rather than an empty one. The three dispatch rows are the convention's
// boundary cases: mode carries its real string default, and an absent yaml int is
// indistinguishable from 0 (which the accessor therefore reads as unset), so each
// carries its real built-in value rather than
// the typed-empty placeholder the convention forbids. reap_done is the sharpest of
// the three — its default is TRUE, so the config struct models it as a *bool to
// keep an explicit false distinguishable from absent. See docs/specs/config.md
// § Default semantics.
//
// Render() output is BYTE-STABLE for a given binary version: the field table is
// fixed and ordered, the interpolated role/stage lists come from the
// already-sorted agent.RoleNames/agent.StageNames accessors, and no map is
// range-iterated during rendering. RenderJSON() is byte-stable for the same
// reasons (ordered table, deterministic marshalling).
