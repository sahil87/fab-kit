// Scope is a field's override visibility across the config cascade layers. The
// type and its three values are SINGLE-SOURCED in the leaf package
// internal/configscope (the config loader consumes the same source cycle-free);
// they are aliased here so the registry and the cascade share one definition. As
// of Change 2 (lpb5) the cascade resolver PRUNES a project-scoped field found in
// the system file (with a warning), while system init and upgrade render only
// system/both fields. See docs/specs/config.md § Scope taxonomy.
type Scope = configscope.Scope

const (
	// ScopeProject: overridable only in the project file (fab/project/config.yaml).
	// Semantics-class fields stay repo-reproducible for teammates/CI.
	ScopeProject = configscope.ScopeProject
	// ScopeSystem: overridable only in the system file (~/.fab-kit/config.yaml).
	// (No field is system-only today; the value exists for completeness.)
	ScopeSystem = configscope.ScopeSystem
	// ScopeBoth: overridable in either layer (preference-class fields).
	ScopeBoth = configscope.ScopeBoth
)

// validScope reports whether s is one of the three known scope values. Used by
// the registry lint (a scope outside this set is a fail-loud construction error).
// Delegates to the single-source leaf package.
func validScope(s Scope) bool {
	return configscope.Valid(s)
}

// scopeFor returns the scope for a registry row's dotted Key by collapsing it to
// its top-level YAML key (e.g. "project.name" → "project") and consulting the
// single-source leaf table. Every registry Key's top-level segment is a known
// scope key; an unknown one is a construction bug and is caught by the lint
// (scopeFor returns "" for unknown, which validScope rejects).
func scopeFor(key string) Scope {
	top := key
	if i := strings.IndexByte(key, '.'); i >= 0 {
		top = key[:i]
	}
	s, ok := configscope.ScopeFor(top)
	if !ok {
		return "" // lint rejects the empty scope, surfacing the missing taxonomy entry
	}
	return s
}

// Field is one row of the per-field metadata table — the single source the two
// renderings (commented YAML, JSON) are both generated from. It models the
// override UNIT (a meaningful override surface), which is coarser than a leaf
// key: map-valued fields (CLIs, agent.profiles, stage_hooks) are single rows
// with structured defaults, matching the downstream per-field deep-merge (maps
// merge per-key, lists replace, scalars replace).
type Field struct {
	// Key is the dotted path of the override surface (e.g. "agent.profiles",
	// "project.name", "true_impact_exclude"). It is the identity used by the
	// JSON dump and the JSON/YAML key-parity check.
	Key string
	// Default is the CANONICAL built-in default (typed), NOT a rendering example.
	// nil means "no built-in default" (the cascade falls back to empty/absent) —
	// e.g. source_paths/test_paths, whose shown values are examples only. A typed
	// empty is never used for "no default"; see the package-doc empty-default
	// convention.
	Default any
	// Kind is the YAML value shape accepted when this override unit is set as a
	// whole. Deep paths beneath map-valued rows are resolved separately by
	// ResolveKey, which returns their leaf kind.
	Kind configvalue.Kind
	// Description is the one-line summary of the field. Required (non-empty) —
	// the registry lint rejects an empty description. It feeds the JSON dump and
	// the future generated comment scaffold (Change 3). This is the short summary;
	// the long-form documentation prose lives in Segment (the rendered YAML block).
	Description string
	// Scope is the field's override visibility (project/system/both). Data-only
	// here; enforced in Change 2.
	Scope Scope
	// Advertise is the "C flag": whether Change 3's managed fence scaffolds this
	// field as a commented reference when it is not overridden. NO behavioral
	// consumer in this change — data + JSON exposure only.
	Advertise bool
	// RenamedFrom is the previous key path for mechanical rename carry-forward.
	// Two rows carry it today — `agent.profiles`, recording the 260806-j9nh rename
	// from `agent.tiers`, and `clis`, recording the 261120-f2ly rename from
	// `providers`; every other row is "". The carry is a top-level-key operation, so
	// `clis` is carried mechanically by `fab config upgrade` while a same-top-level
	// rename like `agent.tiers` still ships a hand-written migration. Omitted from
	// the JSON dump when empty.
	RenamedFrom string
	// InitSeed marks an A-class IDENTITY field written LIVE at `fab config init
	// --project` time from a seed value (the project's name/description/source/test
	// paths). These are the only fields the generator writes above the managed
	// fence on a fresh repo; every other field is fence territory from day one
	// (presence=intent — an init-pinned knob or role profile would be an accidental override that
	// stops tracking fab-kit's defaults). Consumed by the init generator; not part
	// of the JSON schema dump.
	InitSeed bool
	// Segment is the rendered commented-YAML block that documents this field in
	// the reference — the field's own lines (leading comment prose + the live or
	// commented key), WITHOUT a trailing newline or the inter-field blank line.
	// Render() concatenates the segments in table order (blank line between). For
	// the symbol-backed fields (CLIs, the agent: block, stage_hooks) the segment
	// is built by interpolating the same Go symbols Default reads, so the
	// rendered text carries no literal copy of any value. Not exposed in the JSON
	// dump (it is the human-readable rendering of the same metadata).
	//
	// This is the LONG form: `fab config explain` (bare via Render, keyed via
	// RenderKey) prints it with the full prose. File-bound renderers consume
	// ShortSegment instead (see the package doc's SHORT vs. LONG SEGMENTS).
	Segment string
	// ShortSegment is the file-bound short form of Segment: a short description
	// carrying the row's [project|system|both] scope tag, a
	// `fab config set --system <key> <value>` pointer line for scope-both fields,
	// and a `fab config explain <key>` pointer to the long form, above the same
	// YAML block. It is what the managed fence (configupgrade), the
	// `fab config init --system` scaffold (cmd/fab), and the set/unset
	// materializer render into generated files — the prose diet of 260809-wll4
	// R6/R7. Required on every row that carries a Segment (the lint enforces the
	// pair, the scope tag, and the explain pointer); empty only on rows rendered
	// inside another field's block.
	ShortSegment string
}

// jsonField is the JSON projection of a Field: stable snake_case keys and
// renamed_from,omitempty (carried by one row today — agent.profiles — and absent
// from every other row's dump). Segment is intentionally excluded — it is the YAML rendering of
// the same metadata, not part of the machine-readable schema. Kept separate from
// Field so the Go struct-field names stay idiomatic while the wire shape stays
// snake_case and stable for Changes 2-3.
type jsonField struct {
	Key         string `json:"key"`
	Default     any    `json:"default"`
	Description string `json:"description"`
	Scope       Scope  `json:"scope"`
	Advertise   bool   `json:"advertise"`
	RenamedFrom string `json:"renamed_from,omitempty"`
}

// roleProfileDefault is the structured canonical default for one agent role —
// what lands in the agent.profiles row's Default (and the JSON dump). Sourced from
// agent.DefaultProfile; never a literal copy.
type roleProfileDefault struct {
	CLI    string `json:"cli"`
	Model  string `json:"model"`
	Effort string `json:"effort"`
}

// cliProfileDefault is one built-in per-role fill on a CLI — the
// `clis.<name>.profiles.<role>` value. Both fields are `omitempty` so a fill
// that carries only a model does not assert an empty effort.
type cliProfileDefault struct {
	Model  string `json:"model,omitempty"`
	Effort string `json:"effort,omitempty"`
}

// cliDefault is the structured canonical default for ONE built-in CLI.
// Every field is `omitempty` because a built-in may legitimately carry only some.
// Native is capability data rather than a CLI-name inference. That
// matches the registry's empty-default convention: a non-nil Default always denotes
// a real built-in value, so an absent key means "fab-kit ships none", not "empty" —
// which is also why a sparse fill map (agy) omits the roles it does not fill
// rather than emitting empty objects for them.
//
// The DEPRECATED flat fill (clis.<name>.model/.effort) is deliberately not
// projected: no built-in carries it, and it exists only as a read-time alias for
// profiles.default until the 2.16.19-to-2.17.0 migration rewrites a user's config.
type cliDefault struct {
	InteractiveCommand string                       `json:"interactive_command,omitempty"`
	HeadlessCommand    string                       `json:"headless_command,omitempty"`
	ModelsCommand      string                       `json:"models_command,omitempty"`
	Native             bool                         `json:"native,omitempty"`
	Profiles           map[string]cliProfileDefault `json:"profiles,omitempty"`
}

// cliDefaults is the structured canonical default for the CLIs row:
// every built-in CLI fab-kit ships, DERIVED from the agent package's own
// table rather than from a hand-maintained name list. Walking
// agent.CLINames(nil) and resolving each through agent.ResolveCLI(nil,
// …) — both nil-safe, and a nil *config.Config resolves exactly the built-in set
// with no project overrides — means the JSON dump advertises precisely the set
// `agent.ResolveCLI` resolves with no config, and adding or renaming a
// built-in in defaults.yaml needs no edit here.
//
// Like roleRows, it fails loud on table drift — a name CLINames reports must
// resolve.
func cliDefaults() (map[string]cliDefault, error) {
	names := agent.CLINames(nil)
	defaults := make(map[string]cliDefault, len(names))
	for _, name := range names {
		p, ok := agent.ResolveCLI(nil, name)
		if !ok {
			return nil, fmt.Errorf("configref: CLI %q from agent.CLINames does not resolve via agent.ResolveCLI", name)
		}
		var profiles map[string]cliProfileDefault
		if len(p.Profiles) > 0 {
			profiles = make(map[string]cliProfileDefault, len(p.Profiles))
			for role, fill := range p.Profiles {
				profiles[role] = cliProfileDefault{Model: fill.Model, Effort: fill.Effort}
			}
		}
		defaults[name] = cliDefault{
			InteractiveCommand: p.InteractiveCommand,
			HeadlessCommand:    p.HeadlessCommand,
			ModelsCommand:      p.ModelsCommand,
			Native:             p.Native,
			Profiles:           profiles,
		}
	}
	return defaults, nil
}

// roleRow is one resolved role: its name and its default {cli, model, effort}
// profile (from agent.DefaultProfile). It is the single per-role view both the
// agent.profiles Default (as roleProfileDefault) and the rendered `agent:` Segment
// are built from — one walk of agent.RoleNames(), no duplicated loop.
type roleRow struct {
	Name    string
	Profile roleProfileDefault
}

// roleRows returns the ordered per-role view, one row per agent.RoleNames()
// entry (sorted, so deterministic). It is the SINGLE source that both the
// agent.profiles Default and the rendered `agent:` Segment consume — there is no
// second RoleNames/DefaultProfile loop. It fails loud on role-map drift: a role
// agent.RoleNames reports must resolve through agent.DefaultProfile.
func roleRows() ([]roleRow, error) {
	names := agent.RoleNames()
	rows := make([]roleRow, 0, len(names))
	for _, name := range names {
		p, ok := agent.DefaultProfile(name)
		if !ok {
			return nil, fmt.Errorf("configref: role %q from agent.RoleNames does not resolve via agent.DefaultProfile", name)
		}
		rows = append(rows, roleRow{
			Name:    name,
			Profile: roleProfileDefault{CLI: p.CLI, Model: p.Model, Effort: p.Effort},
		})
	}
	return rows, nil
}

// roleProfileDefaults projects roleRows into the map keyed by role name that the
// agent.profiles Field.Default carries (and the JSON dump emits).
func roleProfileDefaults(rows []roleRow) map[string]roleProfileDefault {
	out := make(map[string]roleProfileDefault, len(rows))
	for _, r := range rows {
		out[r.Name] = r.Profile
	}
	return out
}

