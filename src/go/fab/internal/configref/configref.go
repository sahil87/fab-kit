// lintFields is the fail-loud registry validation: every row must have a
// non-empty Description and a valid Scope. A violation is a construction bug
// (a new row added without metadata), caught here rather than shipped as a
// degraded reference — the same discipline as the role-profile invariant above.
func lintFields(fields []Field) error {
	for _, f := range fields {
		if f.Description == "" {
			return fmt.Errorf("configref: field %q has an empty description (every registry row must document its field)", f.Key)
		}
		if !validScope(f.Scope) {
			return fmt.Errorf("configref: field %q has invalid scope %q (want one of project/system/both)", f.Key, f.Scope)
		}
		if !configvalue.Valid(f.Kind) {
			return fmt.Errorf("configref: field %q has invalid value kind %q", f.Key, f.Kind)
		}
		// Single-source guard: the row's Scope MUST equal the leaf-package
		// taxonomy for the field's top-level key. The loader (internal/config)
		// prunes the system layer on that same leaf table, so a divergence here
		// would silently split the scope taxonomy in two. Fail loud at
		// construction instead. See internal/configscope.
		if want := scopeFor(f.Key); f.Scope != want {
			return fmt.Errorf("configref: field %q has scope %q but internal/configscope says %q — the scope taxonomy is single-sourced in configscope; fix it there", f.Key, f.Scope, want)
		}
	}
	return nil
}

// KeyMatch is the registry resolution for an exact key or supported deep path.
// Field is the override-unit row that supplies scope and schema ownership;
// Owner is the row whose Segment renders the key; Kind is the exact value kind
// accepted at the requested path.
type KeyMatch struct {
	Field Field
	Owner Field
	Kind  configvalue.Kind
}

// ResolveKey validates a dotted config key against the registry. Map-valued
// rows accept only their documented dynamic axes, so plausible typos do not
// become silent writes. Quoted/escaped key spellings are deliberately refused;
// the command surface accepts canonical unquoted dotted paths only.
func ResolveKey(key string) (KeyMatch, bool, error) {
	fields, err := Fields()
	if err != nil {
		return KeyMatch{}, false, err
	}
	parts := strings.Split(key, ".")
	if len(parts) >= 2 && parts[0] == "providers" {
		if reason := invalidProviderName(parts[1]); reason != "" {
			return KeyMatch{}, false, fmt.Errorf(
				"config key %q uses provider name %q, which cannot be represented by the dotted config-key grammar: %s",
				key, parts[1], reason,
			)
		}
	}
	if !validDottedKey(key) {
		return KeyMatch{}, false, nil
	}

	for i, field := range fields {
		if field.Key == key {
			return KeyMatch{Field: field, Owner: segmentOwner(fields, i), Kind: field.Kind}, true, nil
		}
	}
	// Structural parents of registry rows are real mapping keys too (`project`,
	// `agent`, `dispatch`, ...), even though the registry models their children as
	// separate override units.
	for i, field := range fields {
		if strings.HasPrefix(field.Key, key+".") {
			return KeyMatch{Field: field, Owner: segmentOwner(fields, i), Kind: configvalue.KindMapping}, true, nil
		}
	}

	switch {
	case len(parts) == 3 && parts[0] == "agent" && parts[1] == "profiles" &&
		contains(agent.RoleNames(), parts[2]):
		return dynamicMatch(fields, "agent.profiles", configvalue.KindMapping)

	case len(parts) == 4 && parts[0] == "agent" && parts[1] == "profiles" &&
		contains(agent.RoleNames(), parts[2]) && contains([]string{"provider", "model", "effort"}, parts[3]):
		return dynamicMatch(fields, "agent.profiles", configvalue.KindString)

	case len(parts) == 2 && parts[0] == "providers":
		return dynamicMatch(fields, "providers", configvalue.KindMapping)

	case len(parts) == 3 && parts[0] == "providers" &&
		contains([]string{"interactive_command", "headless_command"}, parts[2]):
		return dynamicMatch(fields, "providers", configvalue.KindString)

	case len(parts) == 3 && parts[0] == "providers" && parts[2] == "profiles":
		return dynamicMatch(fields, "providers", configvalue.KindMapping)

	case len(parts) == 4 && parts[0] == "providers" && parts[2] == "profiles" && contains(agent.RoleNames(), parts[3]):
		return dynamicMatch(fields, "providers", configvalue.KindMapping)

	case len(parts) == 5 && parts[0] == "providers" && parts[2] == "profiles" &&
		contains(agent.RoleNames(), parts[3]) && contains([]string{"model", "effort"}, parts[4]):
		return dynamicMatch(fields, "providers", configvalue.KindString)

	case len(parts) == 2 && parts[0] == "stage_hooks" && contains(agent.StageNames(), parts[1]):
		return dynamicMatch(fields, "stage_hooks", configvalue.KindMapping)

	case len(parts) == 3 && parts[0] == "stage_hooks" &&
		contains(agent.StageNames(), parts[1]) && contains([]string{"pre", "post"}, parts[2]):
		return dynamicMatch(fields, "stage_hooks", configvalue.KindString)
	}

	return KeyMatch{}, false, nil
}

func dynamicMatch(fields []Field, fieldKey string, kind configvalue.Kind) (KeyMatch, bool, error) {
	for i, field := range fields {
		if field.Key == fieldKey {
			return KeyMatch{Field: field, Owner: segmentOwner(fields, i), Kind: kind}, true, nil
		}
	}
	return KeyMatch{}, false, fmt.Errorf("configref: dynamic key owner %q is missing from the registry", fieldKey)
}

func segmentOwner(fields []Field, index int) Field {
	if fields[index].Segment != "" {
		return fields[index]
	}
	top := topLevel(fields[index].Key)
	for i := index - 1; i >= 0; i-- {
		if topLevel(fields[i].Key) != top {
			break
		}
		if fields[i].Segment != "" {
			return fields[i]
		}
	}
	return fields[index]
}

func validDottedKey(key string) bool {
	if key == "" || key != strings.TrimSpace(key) {
		return false
	}
	parts := strings.Split(key, ".")
	for index, part := range parts {
		if part == "" {
			return false
		}
		// Provider names are user-defined map keys, not schema identifiers. Keep
		// the surrounding providers/profiles/role/leaf axes strict while accepting
		// any canonical unquoted segment on this one dynamic axis.
		if len(parts) >= 2 && parts[0] == "providers" && index == 1 {
			if !validProviderName(part) {
				return false
			}
			continue
		}
		for i := 0; i < len(part); i++ {
			c := part[i]
			letter := c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z'
			if letter || c == '_' || (i > 0 && (c >= '0' && c <= '9' || c == '-')) {
				continue
			}
			return false
		}
	}
	return true
}

func validProviderName(name string) bool {
	return invalidProviderName(name) == ""
}

// invalidProviderName keeps the dotted CLI grammar unambiguous. Provider names
// remain opaque (digits, bool-like words, a leading hyphen, and Unicode are all
// accepted); the mutation writer quotes their on-disk YAML key when needed.
func invalidProviderName(name string) string {
	if name == "" {
		return "the name is empty"
	}
	if name != strings.TrimSpace(name) {
		return "leading or trailing whitespace requires quoting"
	}
	for _, r := range name {
		if unicode.IsSpace(r) || unicode.IsControl(r) {
			return "whitespace and control characters require quoting"
		}
		// Dots are path separators. The remaining characters are YAML indicators
		// or quoted/escaped spellings that would make the dotted input ambiguous.
		if strings.ContainsRune(".:,[]{}#&*!|>'\"%@`\\", r) {
			return fmt.Sprintf("character %q requires quoting", r)
		}
	}
	return ""
}

func contains(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}

func topLevel(key string) string {
	if i := strings.IndexByte(key, '.'); i >= 0 {
		return key[:i]
	}
	return key
}

// FieldsForKey returns every registry row represented by the requested key's
// owning rendered segment, in registry order. This is the keyed JSON explain
// projection; a one-row segment returns a one-element slice.
func FieldsForKey(key string) ([]Field, error) {
	match, ok, err := ResolveKey(key)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, fmt.Errorf("unknown config key %q", key)
	}
	fields, err := Fields()
	if err != nil {
		return nil, err
	}
	var out []Field
	started := false
	for _, field := range fields {
		if field.Key == match.Owner.Key {
			started = true
		}
		if !started {
			continue
		}
		if len(out) > 0 && field.Segment != "" {
			break
		}
		out = append(out, field)
	}
	return out, nil
}

// RenderKey returns only the owning YAML segment for key.
func RenderKey(key string) (string, error) {
	match, ok, err := ResolveKey(key)
	if err != nil {
		return "", err
	}
	if !ok || match.Owner.Segment == "" {
		return "", fmt.Errorf("unknown config key %q", key)
	}
	return match.Owner.Segment + "\n", nil
}

// RenderJSONKey returns the rows represented by key's owning segment using the
// same deterministic object shape as RenderJSON.
func RenderJSONKey(key string) (string, error) {
	fields, err := FieldsForKey(key)
	if err != nil {
		return "", err
	}
	return renderJSONFields(fields)
}

// FieldKeys returns the dotted key paths of every registry row, in table order.
// Used by the JSON/YAML key-parity guard and any external consumer needing the
// documented key set.
func FieldKeys() ([]string, error) {
	fields, err := Fields()
	if err != nil {
		return nil, err
	}
	keys := make([]string, len(fields))
	for i, f := range fields {
		keys[i] = f.Key
	}
	return keys, nil
}

// InitSeedKeys returns the dotted keys of the A-class IDENTITY fields written live
// at `fab config init --project` time (InitSeed rows), in table order. These are
// the only fields the init generator emits above the managed fence; everything
// else is fence territory from day one. Used by the init generator and its tests.
func InitSeedKeys() ([]string, error) {
	fields, err := Fields()
	if err != nil {
		return nil, err
	}
	var keys []string
	for _, f := range fields {
		if f.InitSeed {
			keys = append(keys, f.Key)
		}
	}
	return keys, nil
}

// Render returns the fully-commented reference config.yaml, generated by walking
// the field registry: the fixed header followed by each row's rendered Segment in
// table order, one blank line between blocks. The output is byte-stable for a
// given binary version and is what `fab config explain` prints to stdout. It
// returns an error rather than emitting partial/degraded output if an invariant
// breaks (Fields surfaces the role-map drift and the registry lint), so a future
// edit that breaks an invariant fails loudly instead of silently shipping a
// malformed reference.
//
// The emitted text is contract-equivalent to the pre-metadata-table renderer
// (same key coverage, live/commented split, and every documented-semantics prose
// block the tests assert verbatim) — the restructure changed the SOURCE of the
// reference (prose template → metadata table walked here), not its output
// contract.
func Render() (string, error) {
	fields, err := Fields()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(referenceHeader)
	for _, f := range fields {
		if f.Segment == "" {
			// A field rendered inside another field's block (e.g. project.description
			// / project.linear_workspace live in the project.name segment) carries no
			// segment of its own — skip it in the walk.
			continue
		}
		b.WriteString("\n\n")
		b.WriteString(f.Segment)
	}
	b.WriteString("\n")
	return b.String(), nil
}

// RenderJSON returns the field registry as a machine-readable JSON array — the
// tooling surface Changes 2-3 and external tools consume. It is a flat array in
// table (rendering) order, each element a per-field object
// {key, default, description, scope, advertise, renamed_from(omitempty)}.
// Deterministic and byte-stable like Render(): the table is ordered and the
// marshalling is stable. Two-space indented with a trailing newline. Segment is
// excluded — it is the YAML rendering, not part of the machine-readable schema.
func RenderJSON() (string, error) {
	fields, err := Fields()
	if err != nil {
		return "", err
	}
	return renderJSONFields(fields)
}

func renderJSONFields(fields []Field) (string, error) {
	view := make([]jsonField, len(fields))
	for i, f := range fields {
		view[i] = jsonField{
			Key:         f.Key,
			Default:     f.Default,
			Description: f.Description,
			Scope:       f.Scope,
			Advertise:   f.Advertise,
			RenamedFrom: f.RenamedFrom,
		}
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(view); err != nil {
		return "", fmt.Errorf("configref: marshalling reference JSON: %w", err)
	}
	return buf.String(), nil
}
